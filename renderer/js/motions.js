class MotionPlayer {
  constructor(character) {
    this.ch = character;
    this.current = null;
    this.t = 0;
    this._snapshot = null;
  }

  list() { return Object.keys(MOTIONS); }

  /** adjust: { パラメータ: 足す量 } — 相手に合わせてモーションを少し変える(手を伸ばす高さなど)。
   *  モーションのトラックにあるパラメータだけ。入り 20%・抜け 22% でなめらかに足す */
  play(name, adjust = null) {
    const m = MOTIONS[name];
    if (!m) { console.warn('unknown motion:', name); return false; }
    this.current = m;
    this.adjust = adjust;
    this.t = 0;
    // 現在値からの相対再生ではなく、基準ポーズ上で加算合成する
    return true;
  }

  playRandom(pool) {
    const names = pool && pool.length ? pool : this.list();
    return this.play(names[Math.floor(Math.random() * names.length)]);
  }

  stop() { this.current = null; }

  /** dt秒進めて character.p にポーズを書き込む(update()の前に呼ぶ) */
  step(dt) {
    const p = this.ch.p, base = this.ch._base;
    // まず基準ポーズへ緩やかに戻す(モーションが無いパラメータも自然に復帰)
    for (const k in base) {
      if (k === 'eyeX' || k === 'eyeY' || k === 'mouthOpen') continue; // 外部駆動は触らない
      p[k] += (base[k] - p[k]) * Math.min(1, dt * 6);
    }
    if (!this.current) return;

    this.t += dt;
    const u = this.t / this.current.dur;
    if (u >= 1) { this.current = null; return; }

    for (const [param, keys] of Object.entries(this.current.tracks)) {
      // キーフレーム区間を探して補間
      let v = keys[keys.length - 1][1];
      for (let i = 0; i < keys.length - 1; i++) {
        const [t0, v0] = keys[i], [t1, v1] = keys[i + 1];
        if (u >= t0 && u <= t1) {
          const k = ease((u - t0) / Math.max(1e-6, t1 - t0));
          v = v0 + (v1 - v0) * k;
          break;
        }
      }
      if (param === 'blush' || param === 'mouthSmile' || param === 'browY'
          || param === 'blink' || param === 'winkL' || param === 'winkR'
          || param === 'mouthOpen' || param === 'eyeX' || param === 'eyeY') {
        this.ch.p[param] = v;              // 絶対値系
      } else {
        this.ch.p[param] = base[param] + v; // ポーズ系は基準+オフセット
      }
    }
    if (this.adjust) {
      const k = u < 0.2 ? ease(u / 0.2) : u < 0.78 ? 1 : 1 - ease((u - 0.78) / 0.22);
      for (const [param, d] of Object.entries(this.adjust))
        if (this.current.tracks[param]) this.ch.p[param] += d * k;
    }
  }
}
